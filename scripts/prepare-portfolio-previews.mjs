import sharp from 'sharp';
import { mkdir, readFile, writeFile, stat } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

// Keep previews separate from the full-size originals used by the lightbox.
const root = new URL('../', import.meta.url);
const source = await readFile(new URL('src/data/portfolio.ts', root), 'utf8');
const assets = new Map();
for (const match of source.matchAll(/import\s+(\w+)\s+from\s+"(@\/assets\/[^"\n]+\.(?:png|jpg|webp))"/g)) {
  assets.set(match[2], { key: `preview${assets.size}`, file: match[2].replace('@/', 'src/') });
}
for (const match of source.matchAll(/(?:image|src):\s*"(\/[^"\n]+\.(?:png|jpg|webp))"/g)) {
  assets.set(match[1], { key: JSON.stringify(match[1]), file: `public${match[1]}` });
}
if (!assets.size) throw new Error('No portfolio assets found; inspect the data module before generating previews.');
const output = new URL('public/work/portfolio/', root);
await mkdir(output, { recursive: true });
const imports = [];
const entries = [];
let originalBytes = 0;
let previewBytes = 0;
for (const [path, asset] of assets) {
  if (path.startsWith('@/')) imports.push(`import ${asset.key} from ${JSON.stringify(path)};`);
  const input = fileURLToPath(new URL(asset.file, root));
  originalBytes += (await stat(input)).size;
  const slug = path.replace(/^@\/assets\/|^\//, '').replace(/\.[^.]+$/, '').replace(/[^a-zA-Z0-9-]/g, '-');
  const variants = [];
  for (const width of [480, 960]) {
    const name = `${slug}-${width}.webp`;
    const info = await sharp(input).rotate().resize({ width, withoutEnlargement: true }).webp({ quality: 80 }).toFile(fileURLToPath(new URL(name, output)));
    previewBytes += info.size;
    if (!variants.some(item => item.width === info.width)) variants.push({ src: `/work/portfolio/${name}`, width: info.width });
  }
  entries.push(`  [${asset.key}]: ${JSON.stringify({ src: variants[0].src, srcSet: variants.map(v => `${v.src} ${v.width}w`).join(', ') })},`);
}
await writeFile(new URL('src/data/portfolio-previews.ts', root), `// Generated by scripts/prepare-portfolio-previews.mjs.\n${imports.join('\n')}\n\nexport const portfolioPreviews: Record<string, { src: string; srcSet: string }> = {\n${entries.join('\n')}\n};\n`);
console.log(JSON.stringify({ images: assets.size, originalBytes, previewBytes }));
